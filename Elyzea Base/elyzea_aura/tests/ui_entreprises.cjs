// Test de l'appli ENTREPRISES (aperçu navigateur du téléphone, données de démonstration, Chromium headless)
// NODE_PATH=$(npm root -g) node tests/ui_entreprises.cjs [dossier captures]
const { chromium } = require('playwright');
const path = require('path');
const out = process.argv[2] || path.join(__dirname, 'shots');
require('fs').mkdirSync(out, { recursive: true });
let fails = 0;
const check = (c, l) => { console.log(`  ${c ? 'ok  ' : 'ÉCHEC'} ${l}`); if (!c) fails++; };
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 900, height: 900 }, deviceScaleFactor: 2 });
  const errs = []; p.on('pageerror', (e) => errs.push(e.message));
  const reqs = [];
  await p.route(/^https?:/, (r) => r.abort());
  await p.goto('file://' + path.join(__dirname, '..', 'html', 'index.html'));
  await p.waitForTimeout(6000);
  await p.exposeFunction('__req', (n, a) => reqs.push({ n, a }));
  await p.evaluate(() => {
    const M = window.__elyzea.Mock, h = M.handle.bind(M);
    M.handle = (ep, d) => { if (ep === 'request') window.__req(d.name, d.args); return h(ep, d); };
    const c = EntMock.call; EntMock.call = (n, a) => { window.__req(n, a); return c(n, a); };
    window.__opened = []; window.open = (u) => { window.__opened.push(u); };
    const E = window.__elyzea; E.S.settings.setup = true; E.S.settings.theme = 'dark'; document.getElementById('screen').classList.remove('in-setup');
    document.getElementById('setup').classList.remove('active'); E.applySettings(); E.S.locked = false; E.goHome();
  });
  await p.waitForTimeout(400);
  const shot = (n) => p.locator('#screen').screenshot({ path: path.join(out, `ent_${n}.png`) });
  check(await p.$('[data-open="entreprises"]') !== null, 'icône « Entreprises » sur l\'accueil (sans installation)');
  await shot('00_accueil');
  await p.click('[data-open="entreprises"]'); await p.waitForTimeout(700);
  const tabs = await p.$$eval('[data-ent-tab]', (x) => x.map((t) => t.textContent.trim()));
  check(tabs.join('|') === 'Entreprise|Lancer mon Business', 'onglets « Entreprise » et « Lancer mon Business »');
  check(await p.$$eval('.ent-card', (x) => x.length) === 2, 'annuaire : 2 entreprises');
  const c1 = await p.textContent('.ent-card');
  check(c1.includes('Vinewood') && c1.includes('Événementiel') && c1.includes('2 en service'), 'carte : nom, spécialité, employés en service');
  check(await p.$eval('.ent-card .ent-logo', (e) => getComputedStyle(e).backgroundImage.startsWith('url')), 'logo affiché');
  check(await p.$('.ent-card:nth-child(2) .ent-logo--none') !== null, 'sans logo : initiales');
  await shot('01_annuaire');
  await p.fill('#ent-q', 'sécu'); await p.waitForTimeout(200);
  check(await p.$$eval('.ent-card', (x) => x.length) === 1, 'recherche « sécu » : 1 résultat');
  await p.fill('#ent-q', ''); await p.waitForTimeout(150);
  await p.click('[data-ent-spec="evenementiel"]'); await p.waitForTimeout(150);
  check(await p.$$eval('.ent-card', (x) => x.length) === 1, 'filtre par spécialité');
  await p.click('[data-ent-spec=""]'); await p.waitForTimeout(150);
  await p.click('.ent-card .ent-card__name'); await p.waitForTimeout(500);
  const det = await p.textContent('.sheet');
  check(det.includes('Devis gratuit') && det.includes('919-0001') && det.includes('Léa Moreau'), 'fiche : description complète, numéro, fondateur');
  await shot('02_fiche');
  await p.click('.sheet [data-d-msg]'); await p.waitForTimeout(600);
  check(await p.evaluate(() => window.__elyzea.S.currentApp) === 'messages', 'Message → conversation dans Messages');
  await p.evaluate(() => openApp('entreprises')); await p.waitForTimeout(600);
  await p.click('.ent-card [data-ent-call]'); await p.waitForTimeout(800);
  check(reqs.some((r) => r.n === 'startCall' && r.a && r.a.number === '919-0001') || await p.evaluate(() => !!window.__elyzea.S.call), 'Appeler → appel vers le numéro public');
  await p.evaluate(() => { endCallUI(); openApp('entreprises', { tab: 'launch' }); }); await p.waitForTimeout(700);

  // Lancer mon Business
  const sp = (s) => s.replace(/[\u00a0\u202f]/g, ' ');
  const t = sp(await p.textContent('.app__body'));
  check(t.includes('25 000') && t.includes('Mécano'), 'création : prix et avertissement « vous quitterez votre métier »');
  await shot('03_lancer');
  await p.click('#ent-create'); await p.waitForTimeout(200);
  check((await p.textContent('#ent-err')).includes('nom'), 'sans nom : message d\'erreur');
  await p.fill('#ent-name', 'Los Santos Taxi');
  await p.click('[data-spec="commerce"]');
  await p.click('[data-color="#f97316"]'); await p.waitForTimeout(150);
  check(await p.inputValue('#ent-name') === 'Los Santos Taxi', 'le nom reste après un changement de couleur');
  await p.fill('#ent-desc', 'Taxis 24 h/24 dans tout Los Santos.\nAppelez-nous !');
  check((await p.textContent('#ent-count')) === `${(await p.inputValue('#ent-desc')).length} / 600`, 'compteur de caractères');
  await p.click('#ent-logo-btn'); await p.waitForTimeout(500);
  check(await p.$$eval('.sheet .picker button', (x) => x.length) === 2 && await p.$('.sheet [data-pc]') !== null, 'choix du logo : ordinateur, galerie, lien');
  await shot('04_logo_choix');
  await p.fill('#ent-url', 'javascript:alert(1)'); await p.click('#ent-url-go'); await p.waitForTimeout(150);
  check((await p.textContent('#ent-url-err')).includes('https'), 'lien non https : refusé');
  await p.click('.sheet [data-pc]'); await p.waitForTimeout(700);
  check((await p.evaluate(() => window.__opened)).some((u) => u.includes('/elyzea_entreprises/logo?code=K7P2QD')), 'page d\'import ouverte dans le navigateur (code déjà rempli)');
  check((await p.textContent('.ent-code')).replace(/\s/g, '') === 'K7P2QD', 'code affiché');
  await shot('05_ordinateur');
  await p.waitForTimeout(4500);
  check(await p.$('.sheet') === null || !(await p.textContent('.sheet')).includes('En attente'), 'logo reçu : la fenêtre se ferme');
  check(await p.$eval('.ent-logopick .ent-logo', (e) => getComputedStyle(e).backgroundImage.startsWith('url')), 'logo de l\'ordinateur dans le formulaire');
  check(await p.inputValue('#ent-name') === 'Los Santos Taxi' && (await p.inputValue('#ent-desc')).includes('Appelez'), 'nom et description gardés');
  await shot('06_formulaire');
  await p.click('#ent-create'); await p.waitForTimeout(500);
  check(sp(await p.textContent('.sheet')).includes('25 000') && (await p.textContent('.sheet')).includes('Mécano'), 'confirmation : prix et métier quitté');
  await p.click('.sheet [data-yes]'); await p.waitForTimeout(900);
  const cr = reqs.find((r) => r.n === 'entCreate');
  check(cr && cr.a.name === 'Los Santos Taxi' && cr.a.specialty === 'commerce' && cr.a.color === '#f97316' && cr.a.leaveJob === true && cr.a.logo.startsWith('data:image'), 'création envoyée (nom, spécialité, couleur, logo, métier quitté)');
  const mine = await p.textContent('.app__body');
  check(mine.includes('Los Santos Taxi') && mine.includes('Patron') && mine.includes('F6'), 'onglet devenu « Mon business » (patron, F6)');
  await shot('07_mon_business');
  await p.fill('#ent-desc', 'Nouvelle description de la vitrine !');
  await p.click('#ent-save'); await p.waitForTimeout(700);
  check(reqs.some((r) => r.n === 'entProfile' && r.a.description.includes('Nouvelle')), 'vitrine enregistrée');
  await p.click('[data-ent-tab="list"]'); await p.waitForTimeout(600);
  check(await p.$$eval('.ent-card', (x) => x.length) === 3, 'la nouvelle entreprise apparaît dans l\'annuaire');
  await shot('08_annuaire_apres');
  check(errs.length === 0, `aucune erreur JavaScript (${errs.join(' | ')})`);
  await b.close();
  console.log(fails ? `\n${fails} ÉCHEC(S)` : '\nTOUT EST OK');
  process.exit(fails ? 1 : 0);
})();

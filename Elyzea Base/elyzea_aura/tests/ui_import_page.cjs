// Test de la page web d'import ElyFy (web/elyfy_import.html), faux serveur + faux hébergeur
// NODE_PATH=$(npm root -g) node tests/ui_import_page.cjs [dossier captures]
const { chromium } = require('playwright');
const path = require('path'), fs = require('fs');
const out = process.argv[2] || path.join(__dirname, 'shots');
fs.mkdirSync(out, { recursive: true });
let fails = 0;
const check = (c, l) => { console.log(`  ${c ? 'ok  ' : 'ÉCHEC'} ${l}`); if (!c) fails++; };
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 1100, height: 900 } });
  const errs = []; p.on('pageerror', (e) => errs.push(e.message));
  const html = fs.readFileSync(path.join(__dirname, '..', 'web', 'elyfy_import.html'), 'utf8');
  const calls = [];
  await p.route('http://srv.test/**', async (r) => {
    const u = new URL(r.request().url());
    if (r.request().method() === 'GET') return r.fulfill({ status: 200, contentType: 'text/html', body: html });
    const d = JSON.parse(r.request().postData() || '{}'); calls.push([u.pathname, d]);
    const j = (s, o) => r.fulfill({ status: s, contentType: 'application/json', body: JSON.stringify(o) });
    if (d.code !== 'K7P2QD') return j(403, { ok: false, error: 'Code invalide ou expiré.' });
    if (u.pathname.endsWith('/check')) return j(200, { ok: true, artist: 'Léna D.', maxMb: 15 });
    if (u.pathname.endsWith('/start')) return j(200, { ok: true, uploadUrl: 'https://upload.test/once' });
    if (u.pathname.endsWith('/finish')) return j(200, { ok: true, id: 7 });
  });
  let uploaded = 0;
  await p.route('https://upload.test/**', (r) => { uploaded = (r.request().postDataBuffer() || []).length; r.fulfill({ status: 200, contentType: 'application/json', headers: { 'Access-Control-Allow-Origin': '*' }, body: JSON.stringify({ data: { url: 'https://r2.fivemanage.com/x/mon_son.mp3' } }) }); });
  await p.goto('http://srv.test/elyzea_aura/import');
  const shot = (n) => p.screenshot({ path: path.join(out, `import_${n}.png`) });
  check(await p.$eval('#go1', x => x.disabled), 'code incomplet : bouton désactivé');
  await p.fill('#code', 'zzzzzz'); await p.click('#go1'); await p.waitForTimeout(300);
  check((await p.textContent('#m1')).includes('invalide'), 'mauvais code : message');
  await p.fill('#code', 'k7p-2qd'); await p.waitForTimeout(100);
  check(await p.inputValue('#code') === 'K7P2QD', 'code nettoyé (majuscules, sans tiret)');
  await shot('01_code');
  await p.click('#go1'); await p.waitForTimeout(400);
  check(await p.isVisible('#s2') && (await p.textContent('#who')).includes('Léna D.'), 'étape 2 : connecté en tant que Léna D.');
  const wav = Buffer.alloc(44 + 8000); wav.write('RIFF', 0);
  await p.setInputFiles('#file', { name: 'mon_super_son.mp3', mimeType: 'audio/mpeg', buffer: wav });
  check(await p.inputValue('#title') === 'mon super son' && (await p.textContent('#fname')) === 'mon_super_son.mp3', 'fichier choisi, titre proposé');
  await p.setInputFiles('#file', { name: 'photo.png', mimeType: 'image/png', buffer: Buffer.alloc(10) });
  await p.click('#frm'); await p.setInputFiles('#file', { name: 'photo.png', mimeType: 'image/png', buffer: Buffer.alloc(10) });
  check((await p.textContent('#m2')).includes('pas un fichier audio'), 'fichier non audio refusé');
  await p.setInputFiles('#file', { name: 'mon_super_son.mp3', mimeType: 'audio/mpeg', buffer: wav });
  await p.fill('#title', 'Nuit à Vinewood'); await p.check('#pub');
  await shot('02_fichier');
  await p.click('#go2'); await p.waitForTimeout(900);
  check(uploaded > 8000, 'fichier envoyé à l\'hébergeur');
  const fin = calls.find(c => c[0].endsWith('/finish'));
  check(fin && fin[1].url === 'https://r2.fivemanage.com/x/mon_son.mp3' && fin[1].title === 'Nuit à Vinewood' && fin[1].public === true, 'titre enregistré (lien, titre, publié)');
  check(calls.every(c => c[0].startsWith('/elyzea_aura/import/')), 'adresses relatives à la page (/elyzea_aura/import/…)');
  check(await p.isVisible('#s3') && (await p.textContent('#donet')).includes('publié'), 'confirmation');
  await shot('03_ok');
  await p.click('#again'); await p.waitForTimeout(200);
  check(await p.isVisible('#s2') && await p.inputValue('#title') === '', 'importer un autre morceau avec le même code');
  await p.setViewportSize({ width: 390, height: 800 }); await shot('04_mobile');
  check(errs.length === 0, 'aucune erreur JavaScript' + (errs.length ? ' : ' + errs.join(' | ') : ''));
  console.log(`\n${fails ? fails + ' ÉCHEC(S)' : 'TOUT EST OK'}`);
  await b.close(); process.exit(fails ? 1 : 0);
})();

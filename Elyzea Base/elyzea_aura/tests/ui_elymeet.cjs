// Test de l'interface ElyMeet (aperçu navigateur du téléphone, Chromium headless)
// NODE_PATH=$(npm root -g) node tests/ui_elymeet.cjs [dossier captures]
const { chromium } = require('playwright');
const path = require('path');
const out = process.argv[2] || path.join(__dirname, 'shots');
require('fs').mkdirSync(out, { recursive: true });
let fails = 0;
const check = (c, l) => { console.log(`  ${c ? 'ok  ' : 'ÉCHEC'} ${l}`); if (!c) fails++; };
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 900, height: 900 } });
  const errs = []; p.on('pageerror', (e) => errs.push(e.message + ' @ ' + (e.stack || '').split('\n').slice(1, 3).join(' ')));
  await p.route(/^https?:/, (r) => r.abort());
  await p.goto('file://' + path.join(__dirname, '..', 'html', 'index.html'));
  await p.waitForTimeout(3000);
  await p.evaluate(() => { const E = window.__elyzea; E.S.settings.setup = true; E.S.settings.installed = ['elymeet', 'etincelle']; E.S.settings.theme = 'light'; document.getElementById('screen').classList.remove('in-setup'); document.getElementById('setup').classList.remove('active'); E.applySettings(); E.S.locked = false; E.goHome(); });
  await p.evaluate(() => { const E = window.__elyzea; E.S.profile.device = { model: 3, tier: 3, label: 'ElyAura 3', apps: 'all', exclude: [], store: true }; E.goHome(); });
  await p.waitForTimeout(400);
  const shot = (n) => p.locator('#screen').screenshot({ path: path.join(out, `elymeet_${n}.png`) });
  const wait = (ms = 450) => p.waitForTimeout(ms);
  const noOverflow = async (label) => {
    const r = await p.evaluate(() => { const s = document.getElementById('screen').getBoundingClientRect(); const all = [...document.querySelectorAll('.em *')].filter(e => { const b = e.getBoundingClientRect(); return b.width > 0 && b.height > 0 && (b.right > s.right + 1 || b.left < s.left - 1) && !e.closest('.emap, .em-fresh'); }); return { n: all.length, ex: all.slice(0, 3).map(e => e.className) }; });
    check(r.n === 0, `${label} : rien ne déborde de l'écran${r.n ? ' ' + JSON.stringify(r.ex) : ''}`);
  };

  console.log('— Inscription');
  await p.click('[data-open="elymeet"]'); await wait(700);
  check((await p.textContent('.em-welcome')).includes('croises'), 'écran d\'accueil (concept des croisements)');
  await shot('01_accueil');
  await p.click('#em-start'); await wait(300);
  check(await p.inputValue('#em-name') === 'Léna' && await p.inputValue('#em-age') === '26', 'étape 1 pré-remplie depuis l\'ancien profil Étincelle');
  check((await p.getAttribute('.em-prog i', 'style')).includes('16.6'), 'barre de progression (1/6)');
  await shot('02_etape_nom');
  await p.fill('#em-age', '15'); await wait(100);
  check(await p.$eval('#em-next', b => b.disabled), 'âge sous le minimum : impossible de continuer');
  await p.fill('#em-age', '26'); await p.click('#em-next'); await wait(250);
  check(await p.$('.em-bigopt.on[data-g="woman"]') !== null, 'étape 2 : genre pré-rempli');
  await shot('03_etape_genre');
  await p.click('#em-next'); await wait(250);
  check(await p.$eval('#em-next', b => b.disabled), 'étape 3 : il faut choisir qui rencontrer et ce qu\'on cherche');
  await p.click('[data-s="men"]'); await p.click('[data-l="serious"]'); await wait(100);
  await shot('04_etape_recherche');
  await p.click('#em-next'); await wait(250);
  check(await p.$$eval('.em-slot--on', x => x.length) === 1, 'étape 4 : photo de l\'ancien profil reprise');
  await p.click('.em-slot[data-add]'); await wait(450);
  await p.click('.em-pickgrid [data-i="0"]'); await wait(450);
  check(await p.$$eval('.em-slot--on', x => x.length) === 2, 'photo ajoutée depuis la galerie');
  await p.click('[data-main="1"]'); await wait(150);
  await shot('05_etape_photos');
  await p.click('#em-next'); await wait(250);
  check(await p.$eval('#em-next', b => b.disabled), 'étape 5 : au moins 3 centres d\'intérêt');
  for (const it of ['Cuisine', 'Voyages', 'Musique', 'Surf']) await p.click(`.em-chip[data-v="${it}"]`);
  check((await p.textContent('.em-count')) === '4 / 10', 'compteur des centres d\'intérêt');
  await shot('06_etape_interets');
  await noOverflow('centres d\'intérêt');
  await p.click('#em-next'); await wait(250);
  await p.fill('#em-job', 'Photographe'); await p.fill('#em-bio', 'J\'adore les couchers de soleil à Del Perro.');
  await shot('07_etape_bio');
  await p.click('#em-next'); await wait(500);
  check((await p.textContent('.em-done')).includes('Léna'), 'profil prêt');
  await shot('08_pret');
  await p.click('#em-go'); await wait(700);

  console.log('— Croisés');
  check(await p.$$eval('.em-card', x => x.length) === 3, 'trois personnes croisées');
  check((await p.textContent('.em-card')).includes('Malik') && await p.$('.em-card--bolt') !== null, 'coup de foudre reçu en premier');
  check((await p.textContent('.em-card[data-id="2"] .em-tag--glass')).includes('4 fois'), 'nombre de croisements');
  check((await p.textContent('.em-card[data-id="2"] [data-place]')).includes('·'), 'quand et où (quartier)');
  check((await p.textContent('.em-card[data-id="2"] .em-common')).includes('3 en commun'), 'centres d\'intérêt en commun');
  check(await p.$('.em-card[data-id="4"] [data-write]') !== null, 'crush existant : bouton Écrire');
  await shot('09_croises');
  await noOverflow('fil');
  await p.click('.em-card[data-id="3"] [data-act="pass"]'); await wait(450);
  check(await p.$('.em-card[data-id="3"]') === null, 'Passer : la carte disparaît');

  console.log('— Profil et crush');
  await p.click('.em-card[data-id="2"] [data-prof]'); await wait(700);
  check((await p.textContent('.em-gal__info')).includes('Malik') && (await p.textContent('.em-gal__info')).includes('Chef'), 'profil : nom, âge, métier');
  check(await p.$$eval('.em-gal__bars i', x => x.length) === 2, 'deux photos (barres)');
  await p.click('.em-gal__r'); await wait(300);
  check(await p.$eval('.em-gal img:nth-of-type(2)', i => i.classList.contains('on')), 'appui à droite : photo suivante');
  check(await p.$('.em-mini .emap__tiles') !== null, 'mini-carte du lieu de croisement');
  check(await p.$$eval('.em-chips--ro .em-chip.on', x => x.length) === 3, 'centres d\'intérêt communs en couleur');
  await shot('10_profil');
  await p.click('.em-pbar [data-act="like"]'); await wait(500);
  check(await p.$('.em-match') !== null && (await p.textContent('.em-match')).includes('Crush'), 'j\'aime réciproque : « C\'est un Crush ! »');
  await shot('11_crush');
  await p.click('.em-match [data-w]'); await wait(600);
  check(await p.$('.em-thread') !== null && (await p.textContent('.em-title')).includes('Malik'), 'conversation ouverte');
  await p.fill('#em-msg', 'Salut Malik !'); await p.press('#em-msg', 'Enter'); await wait(300);
  check((await p.textContent('.em-thread')).includes('Salut Malik'), 'message envoyé');
  await shot('12_conversation');
  await p.click('[data-back]'); await wait(400);
  check(await p.$('.em-gal') !== null, 'retour : profil de Malik (maintenant en crush)');
  check(await p.$('.em-pbar [data-write]') !== null, 'profil : bouton Écrire');
  await p.click('.em-gal__back'); await wait(400);

  console.log('— Carte');
  await p.click('.em-nav [data-tab="map"]'); await wait(900);
  check(await p.$$eval('.em-spot', x => x.length) >= 1, 'lieux de croisement sur la carte');
  check((await p.textContent('.em-spot b')).trim() === '2', 'deux personnes croisées au même endroit');
  await shot('13_carte');
  await p.evaluate(() => document.querySelector('.em-spotmk').closest('.emap__mk').click()); await wait(600);
  check(await p.$$eval('.sheet .em-li', x => x.length) === 2, 'liste des personnes croisées à cet endroit');
  await shot('14_carte_lieu');
  await p.evaluate(() => closeSheet(true));

  console.log('— Crushs');
  await p.click('.em-nav [data-tab="crushes"]'); await wait(500);
  check(await p.$$eval('.em-conv', x => x.length) >= 1, 'conversations');
  await shot('15_crushs');
  await noOverflow('crushs');

  console.log('— Mon profil');
  await p.click('.em-nav [data-tab="me"]'); await wait(500);
  check((await p.textContent('.em-meter')).includes('%'), 'profil complété en %');
  await shot('16_mon_profil');
  await p.click('[data-vis]'); await wait(300);
  check(await p.$('[data-vis] .em-switch.on') !== null, 'mode invisible activé');
  await p.click('[data-edit="interests"]'); await wait(400);
  await p.click('.em-chip[data-v="Boxe"]'); await p.click('#em-save'); await wait(500);
  check(await p.$('.em-me') !== null && (await p.textContent('[data-edit="interests"]')).includes('+2'), 'centres d\'intérêt modifiés');
  await p.evaluate(() => { window.__elyzea.S.settings.theme = 'dark'; window.__elyzea.applySettings(); });
  await p.click('.em-nav [data-tab="feed"]'); await wait(500);
  await shot('17_croises_sombre');

  check(errs.length === 0, 'aucune erreur JavaScript' + (errs.length ? ' : ' + errs.join(' | ') : ''));
  console.log(`\n${fails ? fails + ' ÉCHEC(S)' : 'TOUT EST OK'}`);
  await b.close();
  process.exit(fails ? 1 : 0);
})();
